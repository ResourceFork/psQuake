#!/usr/bin/env python3
"""The validator rejects deliberately broken arenas, each for its own reason.

    test_rejects_broken.py --tools-dir tools --ericw data/ericw-tools/bin \\
        --pak data/librequake/id1/pak0.pak --work build/arena-broken --exit-map lq_e1m1

Each broken map is generated by generate_arena.py --break KIND and compiled
with the real compilers (qbsp, vis, light; vis fails on the leaking one, and
the steps after a failure still run). The validator must exit 1, and the
checks it fails must be exactly the expected ones:

    missing-texture  textures   an antechamber plate uses a texture no WAD holds
    leak             leak       the hall's east wall is gone (vis then has no
                                portals, so geometry fails too)
    no-exit          entities   no trigger_changelevel
    cell-in-brush    grid       a pillar stands on grid cell (5,3)
    cell-corner      grid       a 16 x 16 post on a corner four cells share,
                                clear of every cell centre
    pocket           reach      a second grid on a 64-high platform in the
                                hall's south margin, with no way up

The leak is also caught with qbsp's leak file deleted: the validator itself
finds open space outside the map.
"""

import argparse
import os
import re
import subprocess
import sys

EXPECTED = {
    "missing-texture": {"textures"},
    "leak": {"leak", "geometry"},
    "no-exit": {"entities"},
    "cell-in-brush": {"grid"},
    "cell-corner": {"grid"},
    "pocket": {"reach"},
}


def validate(tools, out, exit_map, with_map=True):
    cmd = [sys.executable, "-I", "-B", os.path.join(tools, "validate_bsp.py"),
           "--bsp", os.path.join(out, "psqarena.bsp"), "--exit-map", exit_map]
    if with_map:
        cmd += ["--map", os.path.join(out, "psqarena.map")]
    p = subprocess.run(cmd, capture_output=True, text=True, stdin=subprocess.DEVNULL)
    failed = set(re.findall(r"^FAIL (\w+):", p.stdout, re.M))
    return p.returncode, failed, p.stdout + p.stderr


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tools-dir", required=True)
    ap.add_argument("--ericw", required=True)
    ap.add_argument("--pak", required=True)
    ap.add_argument("--work", required=True)
    ap.add_argument("--exit-map", required=True)
    a = ap.parse_args()

    problems = 0
    for kind, want in EXPECTED.items():
        out = os.path.join(os.path.abspath(a.work), kind)
        subprocess.run([sys.executable, "-I", "-B", os.path.join(a.tools_dir, "compile_arena.py"),
                        "--tools", a.ericw, "--pak", a.pak, "--out", out,
                        "--break", kind, "--keep-going"],
                       stdin=subprocess.DEVNULL, capture_output=True)
        if not os.path.exists(os.path.join(out, "psqarena.bsp")):
            print(f"FAIL {kind}: qbsp wrote no BSP")
            problems += 1
            continue
        rc, failed, text = validate(a.tools_dir, out, a.exit_map)
        ok = rc == 1 and failed == want
        print(f"{'PASS' if ok else 'FAIL'} {kind}: validator exit {rc}, failed {sorted(failed)}, "
              f"expected {sorted(want)}")
        if not ok:
            print(text)
            problems += 1
        if kind == "leak":
            pts = os.path.join(out, "psqarena.pts")
            had_pts = os.path.exists(pts)
            if had_pts:
                os.remove(pts)
            rc, failed, text = validate(a.tools_dir, out, a.exit_map)
            ok = had_pts and rc == 1 and "leak" in failed
            print(f"{'PASS' if ok else 'FAIL'} leak without qbsp's leak file "
                  f"(qbsp wrote one: {had_pts}): failed {sorted(failed)}")
            if not ok:
                print(text)
                problems += 1
    print(f"test_rejects_broken: {len(EXPECTED) + 1} cases, {problems} failed")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
